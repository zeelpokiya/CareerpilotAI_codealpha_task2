from typing import Dict, List, TypedDict


# ============================================================
# CAREERPILOT AI STATE
# ============================================================

class CareerPilotState(TypedDict, total=False):

    # --------------------------------------------------------
    # USER PROFILE
    # --------------------------------------------------------

    name: str

    education: str

    experience: str

    skills: List[str]

    interests: List[str]

    target_role: str

    # --------------------------------------------------------
    # CAREER RECOMMENDATIONS
    # --------------------------------------------------------

    career_recommendations: List[Dict]

    # --------------------------------------------------------
    # SKILL ANALYSIS
    # --------------------------------------------------------

    skill_gaps: List[str]

    skill_analysis: Dict

    # --------------------------------------------------------
    # CAREER READINESS
    # --------------------------------------------------------

    readiness: Dict

    # --------------------------------------------------------
    # LEARNING ROADMAP
    # --------------------------------------------------------

    roadmap: List[Dict]

    # --------------------------------------------------------
    # PROJECT RECOMMENDATIONS
    # --------------------------------------------------------

    project_recommendations: List[Dict]

    # --------------------------------------------------------
    # FINAL AI RESPONSE
    # --------------------------------------------------------

    final_response: str